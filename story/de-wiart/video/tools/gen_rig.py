"""Convert ../../../de-wiart-rig.svg  ->  src/rig/RigArt.tsx  (defs + character art, joints driven by props)."""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1]).read_text()
out = pathlib.Path(sys.argv[2])

defs = re.search(r'<defs>(.*?)</defs>', src, re.S).group(1)
body = src[src.index('<g id="j-root">'):src.index('</g><!-- /root -->') + len('</g>')]

def jsx(s):
    s = re.sub(r'<!--.*?-->', '', s, flags=re.S)
    s = s.replace('class="blink"', 'transform={T.blink}')
    s = re.sub(r'<g id="j-(\w+)" data-j="\w+"', lambda m: f'<g id="j-{m.group(1)}" transform={{T.{m.group(1)}}}', s)
    s = s.replace('<g id="j-root">', '<g id="j-root" transform={T.root}>')
    s = s.replace('class="', 'className="')
    s = re.sub(r'\s(xmlns:xlink|xmlns)="[^"]*"', '', s)
    def camel(m):
        name = m.group(2)
        parts = name.split('-')
        return m.group(1) + parts[0] + ''.join(p.capitalize() for p in parts[1:]) + '='
    s = re.sub(r'(\s)([a-z]+(?:-[a-z]+)+)=', camel, s)
    return s

# keep only gradients/patterns/filters/clips/boot that the character needs (bg ones are harmless)
code = f"""// AUTO-GENERATED by tools/gen_rig.py from de-wiart-rig.svg — do not edit by hand.
import React from 'react';
import type {{RigTransforms}} from './pose';

export const RigDefs: React.FC = () => (
  <defs>{jsx(defs)}</defs>
);

export const RigBody: React.FC<{{T: RigTransforms}}> = ({{T}}) => (
  {jsx(body)}
);
"""
out.write_text(code)
print('wrote', out, len(code))
